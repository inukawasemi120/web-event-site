「まさかこういうことだったとは、さすがに思わないよな〜」

　ハロウィン当日。ルージュは時間通りやってきたブルーに連れて行かれるまま、お祭り会場の空いているテーブルに座らされ、ほら、あれを言え、と促され。あれだよ、この祭りのあれだ、と繰り返される催促に、ええと、トリックオアトリート……？と首を傾げながら口にすれば、えらく満足気な顔をしながらブルーが箱を差し出してきた。

　開けて飛び出してきたのは、その辺の職人顔負けの繊細に飾り付けられたハロウィンカップケーキだ。デコレーションに使われているバタークリームは紫を基調としたハロウィンらしいグラデーションが美しく、どうやって彩色したんだという感じだし、その上に乗っている紅と青の飴細工はこれまた繊細な造形で蝶を象っていて、まさかこんなものまで作れるとは驚きだ。その上、添えられたアイシングクッキーはまるで食べられるルーンの石といったデザインになっており、もっと早くに知っていたら占いの館で売りたかったのに、とルージュはちょっと思った。

「お前の驚いた顔を見られて満足だ」

「君にここまでの才能があったとはね……お菓子作りが得意なのは知っていたけれど」

　バタークリームとケーキ生地をフォークで崩して、口に運ぶ。バターの風味はしっかりするのだが、何が入っているのか、口どけは軽やかでくどくなく、甘すぎずることもなく、いくらでも食べられそうだ。二日間の不審な行動はこれのためか、と、なんとなく消化しきれず過ごしていた気持ちが線でつながって、クリームと一緒に溶けていく。

「食べ切ってしまうのが勿体無いくらいおいしいよ」

「そんなに気に入ったなら、また作ってやる」

　手放しの賛辞に、ブルーは満更でもなさそうだ。

「食べたら一緒に回るか？君さえ良ければ行ってみたいところがあるんだけど」

「構わんが、あまりくだらないのはやめてくれ」

「どうかな……コットン達がやってるらしいモンスターカフェなんだけど」

「モンスターカフェ……」

「キャンディとかペッグとか、あとオオカミみたいなやつもいるらしい。他の学園のモンスターに興味あるし、ハロウィンらしいし、かわいいし、のぞいてみようかなって」

　ふわふわしたもの、嫌いじゃないだろう、とブルーに問えば、ふん、と、否定はされなかった。

 

