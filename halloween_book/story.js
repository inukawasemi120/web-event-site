「私は……私も関係なくはなかったけど、でも普通に友達と遊んでて、そういうことができるのも綱にいがミヤコ市を守ってくれてたからなのに。それなのに、私……」
「倫子、それは、」
言わんとすることを感じ取って綱紀が口を挟もうとするが、倫子が綱紀の手をぎゅっと握ってそれを止めた。自分が謝ってはいけないし、謝らせることなんてもっと、絶対に、ダメだと思っていた。慎重に言葉を選ぶようにしばらく言い悩んでから、再び口を開く。
「綱にいとこうやって一緒にいられて、嬉しい。ここなら綱にいも一人で大変なこと背負わんでええし、綱にいと一緒に色んなことしたい。今日みたいに、お祭りじゃなくても」
「倫子……」
まっすぐ伝えられた言葉は、そのまま綱紀の胸に落ちた。言葉を返す代わりに、綱紀からも手を握り返して、しばらくの間見つめ合う。繋いだ手から、視線から、お互いがお互いを大切に想っている気持ちがあることだけは、確かに感じられた。
あ、それでね、ぱっと手を離して、倫子はこのタイミングにしようと用意していた物を綱紀に渡した。綱紀の両手のひらに乗るくらいの大きさで、可愛く包装された紙袋。倫子からアイコンタクトで開けるよう促される。
「可愛いクッキーや。それと、これは……」
中にはふたつのものが分けて包まれて入っていた。ひとつはハロウィンらしい形や色のクッキー、そしてもうひとつは食べ物ではなく、スポーツの時に手首にはめるようなリストバンドだった。ワンポイントで、綱紀の襟元を彩っている十字のモチーフに似た模様が刺繍されている。
「最初はお菓子だけのつもりやったんやけど。綱にい、たまにバスケとかで遊んどるみたいやったし、リストバンドなら使えていいかなって、郁子にも手伝ってもらって……ハロウィン関係ないやん、て感じだけど、せっかくの思い出作りやし、記念になるものを渡したくて……綱にい？」
段々恥ずかしくなってきて、視線が下がりながらも言葉を付け加えていく倫子。一旦言葉を止めたが綱紀の反応がなく、あれ、と視線を戻そうとすると。急に抱きしめられて、視界が揺れた。
「わ、わ、ちょ、」
「ありがとう。大事に使わせてもらうわ。……ほんまに、ありがとう」
綱にい、兄妹でもはずかしいよ、そう倫子は言いかけて、やめた。代わりにそっと綱紀の体に手を回して応える。綱にいと一緒にここに来れて良かった、そう呟くと、もう少しだけ抱きしめられる力が強くなった。
しばらくして気持ちが落ち着いた後で、二人は気を取り直して祭りを楽しんだ。まだまだ夜まで色々食べたいから、ということで食べるのは控えめに、簡単な企画に参加したり、ちょっと照れながらもフォトスポットで写真を撮ったり。郁子との約束している時間が近づいてきたところで、丁度、綱紀を探しているリアムたちと出会うことができ、倫子はそこで別れて待ち合わせ場所へと向かうことにする。
道中、一緒に準備をしたブルーやバートのことも見かけることができた。
「え、やば、これブルーが作ったの？」
ちょっと引いた様子のルージュが渡されているのは、お店でもなかなか見られないような凝ったデコレーションのカップケーキだ。デコレーションのバタークリームはハロウィンの夜色が芸術的で、その上に紅と青にツヤツヤと輝く蝶を象った飴細工や、ルーンの石を模したアイシングクッキーが飾られている。
「なんだその反応は。いらんなら返せ」
「違う違う、凄すぎて引いてるんだって。うん、味も美味しい。……今までで食べたお菓子で、一番かも。ありがとう、ブルー」
「ふん」
ツンとした態度を取りながら、ルージュ以外の前ではしないであろう頬の緩みを隠せていない。その近くでは、ジョーが目を輝かせながらイカ焼きにかぶりついていた。
「おいし～！わざわざ作ってくれたの！？バート、天才だよ、すっごくおいしい」
「……姉さんは仮装してるから、お菓子も沢山もらえるだろうし、プロのイカ焼きも屋台で出てるし、無理に全部食べる必要はない」
「こんなの、我慢しようと思っても無理だよ！一本しかないの？」
言葉通りあっという間にペロリと平らげていて、キラキラとした瞳でおかわりをねだるジョー。ぱしぱしと目を瞬かせてから、あるよ、とバートは嬉しそうに綻んで、焼いてくると屋台の焼き台を借りに向かっていった。
二人とも楽しそうで、良かった。幸せな気持ちがもっと膨らんで、待ち合わせの場所に近付くにつれ、倫子の足も少しずつ駆け足になる。
「郁子、お待たせ！」
「倫子。……良かった、いい時間を過ごせたみたいやね」
「うん。郁子、ありがとう。郁子も、一緒にいっぱい思い出作ろ！」
手を取り合ってにっこりと笑い合う二人。
どこから行く？さっき見かけて倫子と寄ってみたかったところが……。そうだ、私もあの企画が気になってて、それとあれも食べたいなって……あ、見て、綱にいと写真撮ったんや。あら、素敵、御堂の兄さま、嬉しそう。……
 
愛と平和の神が統べる世界、サガソフィア。あらゆる暴力が禁じられた、理想的なようでちょっと不条理なこの世界。様々な世界から集まった様々な事情を抱えた者たちが、ある者は平和を喜びつつ、ある者は不満を抱えつつ……なんだかんだ、この地を楽しんでいるようだ。

